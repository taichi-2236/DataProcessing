%% import_csv_foxglove
% mcapデータをCSVに変換する．ボール，ロボット，レフェリー情報を変数に格納する．

%%% 1. データ取得
% mcapファイルからjsonを経由してCSVに変換

% データファイル指定（Autoの場合はスキップ）
if ~exist('auto', 'var')
	datafile = "PushDribble_Circ_HeightChangeTest_NoN11.mcap";
end

% mcapファイルをjsonに変換
topics = {};
jsonFile = convert_mcap2json(datafile,'data_json/',topics);
% jsonファイルをCSVに変換
[csvFile, robotIds] = convert_json2csv(which(jsonFile),"data_csv\from_foxglove\",'foxglove_data_');

% datafileにCSVファイルのPathを格納
datafile = csvFile;

%%% 2. CSVファイルを読み出し
% 変換したCSVファイルからデータを読み出す
data = readtable(csvFile);

%%% 3. Visionデータ格納
% Visionから得られるデータを配列に格納
% ボール，ロボットそれぞれのフィルターされた値と生データを格納する
vision_data  = data(strcmp(string(data.topic(:)),'/vision'),:);

% ボールのデータを格納
ball = [...
	vision_data.sequence(:),...
	vision_data.ball_x(:),...
	vision_data.ball_y(:),...
	vision_data.ball_vx(:),...
	vision_data.ball_vy(:),...
];
raw_ball = [...
	vision_data.sequence(:),...
	vision_data.rawBall_x(:),...
	vision_data.rawBall_y(:),...
	vision_data.rawBall_vx(:),...
	vision_data.rawBall_vy(:),...
	vision_data.rawBall_confidence(:),...
];

% BlueRobotのデータを格納
if isfield(robotIds,'blueRobotIds')
	blue_robot = [];
	raw_blue_robot = [];
	for i = 1:numel(robotIds.blueRobotIds)
		id = robotIds.blueRobotIds(i);
		blue_robot_data = [...
			vision_data.sequence(:),...
			vision_data.(sprintf('blueRobot_%d_id',id))(:),...
			vision_data.(sprintf('blueRobot_%d_x',id))(:),...
			vision_data.(sprintf('blueRobot_%d_y',id))(:),...
			vision_data.(sprintf('blueRobot_%d_angle',id))(:),...
			vision_data.(sprintf('blueRobot_%d_vx',id))(:),...
			vision_data.(sprintf('blueRobot_%d_vy',id))(:),...
			vision_data.(sprintf('blueRobot_%d_speed',id))(:),...
		];
		if isempty(blue_robot)
			blue_robot = blue_robot_data;
		else
			blue_robot = cat(3, blue_robot, blue_robot_data);
		end
		
		rawId = robotIds.rawBlueRobotIds(i);
		raw_blue_robot_data = [...
			vision_data.sequence(:),...
			vision_data.(sprintf('rawBlueRobot_%d_id',rawId))(:),...
			vision_data.(sprintf('rawBlueRobot_%d_x',rawId))(:),...
			vision_data.(sprintf('rawBlueRobot_%d_y',rawId))(:),...
			vision_data.(sprintf('rawBlueRobot_%d_angle',rawId))(:),...
			vision_data.(sprintf('rawBlueRobot_%d_vx',rawId))(:),...
			vision_data.(sprintf('rawBlueRobot_%d_vy',rawId))(:),...
			vision_data.(sprintf('rawBlueRobot_%d_speed',rawId))(:),...
			vision_data.(sprintf('rawBlueRobot_%d_confidence',rawId))(:),...
		];
		if isempty(raw_blue_robot)
			raw_blue_robot = raw_blue_robot_data;
		else
			raw_blue_robot = cat(3, raw_blue_robot, raw_blue_robot_data);
		end
	end
end

% YellowRobotのデータを格納
if isfield(robotIds,'yellowRobotIds')
