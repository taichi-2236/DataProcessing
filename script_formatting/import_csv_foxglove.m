			vision_data.(sprintf('yellowRobot_%d_vx',id))(:),...
			vision_data.(sprintf('yellowRobot_%d_vy',id))(:),...
			vision_data.(sprintf('yellowRobot_%d_speed',id))(:),...
		];
		if isempty(yellow_robot)
			yellow_robot = yellow_robot_data;
		else
			yellow_robot = cat(3, yellow_robot, yellow_robot_data);
		end
		
		rawId = robotIds.rawYellowRobotIds(i);
		raw_yellow_robot_data = [...
			vision_data.sequence(:),...
			vision_data.(sprintf('rawYellowRobot_%d_id',rawId))(:),...
			vision_data.(sprintf('rawYellowRobot_%d_x',rawId))(:),...
